//! Embeds the tray icons. Paths come from the icon registry (assets/icons/icons.json): each
//! tray slot lists an output marked `"use": "tray"`. No icon path is written here.
//! If the registry or an icon is missing, an empty slice is embedded and the tray draws a
//! plain fallback dot.

use std::env;
use std::fs;
use std::path::PathBuf;

fn main() {
    let root = PathBuf::from(env::var("CARGO_MANIFEST_DIR").expect("manifest dir")).join("..");
    let icons_dir = root.join("assets").join("icons");
    let registry = icons_dir.join("icons.json");
    println!("cargo:rerun-if-changed={}", registry.display());
    let json: Option<serde_json::Value> = fs::read_to_string(&registry).ok().and_then(|t| serde_json::from_str(&t).ok());
    let slots = [
        ("TRAY_IDLE", "bridge.tray.idle"),
        ("TRAY_TRANSFERRING", "bridge.tray.transferring"),
        ("TRAY_ERROR", "bridge.tray.error"),
        ("TRAY_IDLE_TEMPLATE", "bridge.tray.idle.template"),
        ("TRAY_TRANSFERRING_TEMPLATE", "bridge.tray.transferring.template"),
        ("TRAY_ERROR_TEMPLATE", "bridge.tray.error.template"),
    ];
    let mut code = String::from("// Generated by build.rs from assets/icons/icons.json.\n");
    for (name, slot) in slots {
        let path = json.as_ref().and_then(|j| {
            let outputs = j.get("slots")?.get(slot)?.get("outputs")?.as_array()?;
            let out = outputs.iter().find(|o| o.get("use").and_then(|u| u.as_str()) == Some("tray"))?;
            Some(icons_dir.join(out.get("path")?.as_str()?))
        });
        match path.filter(|p| p.exists()) {
            Some(p) => {
                println!("cargo:rerun-if-changed={}", p.display());
                let s = p.display().to_string().replace('\\', "/");
                code.push_str(&format!("pub const {name}: &[u8] = include_bytes!({s:?});\n"));
            }
            None => code.push_str(&format!("pub const {name}: &[u8] = &[];\n")),
        }
    }
    let out = PathBuf::from(env::var("OUT_DIR").expect("out dir")).join("icons.rs");
    fs::write(out, code).expect("write icons.rs");
}
